// Helper cloner
function cloneTopology(devices: Device[], links: NetworkLink[]): { devices: Device[]; links: NetworkLink[] } {
  return {
    devices: devices.map(d => ({
      ...d,
      interfaces: d.interfaces.map(i => ({ ...i })),
      position: { ...d.position },
    })),
    links: links.map(l => ({ ...l, queue: [], packetsInFlight: [] })),
  };
}

